/**
 * THE TAG KEY, ON THE REPORT TOO — the same four words the seat uses (Amy's ruling (2), 2026-09-24:
 * *"A value carries its tag everywhere it appears."*).
 *
 * The tag is READ OFF THE SOURCE SENTENCE the row already carries, rather than typed a second time
 * beside it. That is deliberate: two hand-kept fields drift, and a tag that disagrees with the
 * source line under it is worse than no tag. The report writes its source lines in a fixed grammar
 * — *"Calculated as per Eq. n"*, *"Methodology V2.0 default — …"*, *"Entered — …"*, *"Project
 * record — …"*, *"Assumption — …"* — and this reads that grammar.
 *
 * ⚠ AN UNRECOGNISED SENTENCE GETS NO TAG RATHER THAN A GUESSED ONE. A wrong tag on a client
 * deliverable is a false claim about where a number came from; a missing one is only a gap. The
 * walk checks for gaps by listing every untagged row (`data-vtag`), so a gap cannot hide.
 */
type ValueTag = "entered" | "default" | "derived" | "assumed";

export function tagForSource(source: string): ValueTag | undefined {
  const s = source.trim();
  if (/^Calculated as per\b/i.test(s) || /^Derived\b/i.test(s) || /^Computed\b/i.test(s)) return "derived";
  // "… 0 assumed ex-ante" is an ASSUMED row wherever the sentence starts, so the word itself
  // decides — and it is checked BEFORE "entered", because "Baseline survey … not yet entered,
  // 0 assumed" names the survey it is waiting for and is still a placeholder today.
  if (/^Assum(ption|ed)\b/i.test(s) || /^Screening preset\b/i.test(s) || /\bassumed\b/i.test(s)) return "assumed";
  if (/^Entered\b/i.test(s) || /^Project record\b/i.test(s) || /^Flow meter\b/i.test(s) || /^Water-quality test\b/i.test(s) || /^Baseline survey\b/i.test(s)) return "entered";
  // "Not applicable — Method 1 (CWT/CWS), U_p = 1 by Eq. 8": the rulebook fixes the value, which
  // is what DEFAULT means here — the methodology's own number, cited.
  if (/^Not applicable\b/i.test(s)) return "default";
  if (/^Methodolog(y|ies)\b/i.test(s) || /\bdefault\b/i.test(s) || /^GS4GG\b/i.test(s) || /^A6\.4-AMT-009\b/i.test(s)) return "default";
  return undefined;
}

